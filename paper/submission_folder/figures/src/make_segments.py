"""Segmentation view of the forecasts (results/v2/analysis/segments, from scripts/v2/segments.py).

Top: two held-out DROID windows (fixed rule, see segments.py). Columns: observed frame t with the SAM 2.1 arm mask and
the ShiftWM transport field on the predicted arm (arrows: source -> target, k=10); the true frame t+10 with its tracked
SAM mask; the arm mask read out of each method's k=10 forecast (nearest-prototype labelling of the forecast DINOv2
features), drawn as a smooth contour on the true future frame, with its IoU against the SAM mask (best in green bold).
Bottom: arm-mask IoU vs. horizon for all methods (95% bootstrap CIs over test episodes), all windows and moving-arm
windows. Also writes tables/generated/segments_numbers.tex (macros quoted in the text).
"""
